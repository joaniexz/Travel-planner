export function filterFoodSpots(
  category: FoodCategory | 'all',
  city: CityId | 'all' = 'all'
): FoodDessertSpot[] {
  logFunctionCall('filterFoodSpots', { category, city });
  return FOOD_DESSERT_SPOTS.filter((spot) => {
    const matchesCategory = category === 'all' || spot.category === category;
    const matchesCity = city === 'all' || spot.city === city;
    return matchesCategory && matchesCity;
  });
}
